-- =============================================================================
-- 5. TRIGGER DE PROTEÇÃO CONTRA EXCLUSÃO EM MASSA DE ATLETAS
-- =============================================================================
CREATE OR REPLACE FUNCTION public.check_safe_atleta_delete()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    -- Impede qualquer exclusão sem código de atleta explicitamente especificado
    IF OLD.codigo IS NULL OR OLD.codigo = '' THEN
        RAISE EXCEPTION 'Exclusão bloqueada: Identificador de atleta inválido.';
    END IF;

    -- Registra automaticamente a exclusão no log de auditoria
    INSERT INTO public.audit_logs (actor_email, action, target_resource, details)
    VALUES (
        COALESCE(current_setting('request.jwt.claims', true)::jsonb->>'email', 'gestao_sistema'),
        'DELETE_ATLETA',
        'atletas',
        jsonb_build_object('codigo', OLD.codigo, 'nome', OLD.nome, 'cpf', OLD.cpf)
    );

    RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_safe_atleta_delete ON public.atletas;
CREATE TRIGGER trg_safe_atleta_delete
BEFORE DELETE ON public.atletas
FOR EACH ROW
EXECUTE FUNCTION public.check_safe_atleta_delete();

-- =============================================================================
-- 6. TRIGGER DE AUDITORIA AUTOMÁTICA EM ALTERAÇÕES DE ATLETAS (INSERT / UPDATE)
-- =============================================================================
CREATE OR REPLACE FUNCTION public.audit_atleta_changes()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
    IF (TG_OP = 'INSERT') THEN
        INSERT INTO public.audit_logs (actor_email, action, target_resource, details)
        VALUES (
            COALESCE(current_setting('request.jwt.claims', true)::jsonb->>'email', 'gestao_sistema'),
            'INSERT_ATLETA',
            'atletas',
            jsonb_build_object('codigo', NEW.codigo, 'nome', NEW.nome, 'status', NEW.status)
        );
        RETURN NEW;
    ELSIF (TG_OP = 'UPDATE') THEN
        INSERT INTO public.audit_logs (actor_email, action, target_resource, details)
        VALUES (
            COALESCE(current_setting('request.jwt.claims', true)::jsonb->>'email', 'gestao_sistema'),
            'UPDATE_ATLETA',
            'atletas',
            jsonb_build_object(
                'codigo', NEW.codigo,
                'nome', NEW.nome,
                'status_antigo', OLD.status,
                'status_novo', NEW.status,
                'validade', NEW.validade
            )
        );
        RETURN NEW;
    END IF;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_audit_atleta_changes ON public.atletas;
CREATE TRIGGER trg_audit_atleta_changes
AFTER INSERT OR UPDATE ON public.atletas
FOR EACH ROW
EXECUTE FUNCTION public.audit_atleta_changes();

