-- 2. GARANTIR A EXISTÊNCIA DAS TABELAS ESSENCIAIS (SEM MODIFICAR AS EXISTENTES)
CREATE TABLE IF NOT EXISTS public.atletas (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    codigo VARCHAR(6) UNIQUE NOT NULL,
    nome TEXT NOT NULL,
    cpf TEXT,
    nascimento TEXT,
    telefone TEXT,
    municipio TEXT,
    categoria TEXT DEFAULT 'AMADOR',
    modalidade TEXT DEFAULT 'SOLO (INDIVIDUAL)',
    status TEXT DEFAULT 'REGULAR',
    clube TEXT,
    federado TEXT,
    validade TEXT DEFAULT '12/2026',
    foto_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.noticias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    categoria TEXT DEFAULT 'INFORMATIVO',
    conteudo TEXT NOT NULL,
    data_publicacao TEXT,
    imagem_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.admin_users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nome TEXT NOT NULL,
    cargo TEXT DEFAULT 'Diretoria',
    email TEXT UNIQUE NOT NULL,
    senha_hash TEXT,
    senha TEXT,
    is_master BOOLEAN DEFAULT false,
    permissions JSONB DEFAULT '[]'::jsonb,
    last_login TIMESTAMP WITH TIME ZONE,
    failed_attempts INT DEFAULT 0,
    locked_until TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.configuracoes (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    chave TEXT UNIQUE NOT NULL,
    valor TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.keep_alive_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pinged_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    source TEXT DEFAULT 'vercel_cron',
    status TEXT DEFAULT 'active'
);

CREATE TABLE IF NOT EXISTS public.audit_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    actor_email TEXT NOT NULL,
    action TEXT NOT NULL,
    target_resource TEXT NOT NULL,
    details JSONB DEFAULT '{}'::jsonb,
    ip_address TEXT,
    user_agent TEXT
);

-- Índices de performance e integridade
CREATE INDEX IF NOT EXISTS idx_atletas_codigo ON public.atletas(codigo);
CREATE INDEX IF NOT EXISTS idx_atletas_status ON public.atletas(status);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created ON public.audit_logs(created_at DESC);

