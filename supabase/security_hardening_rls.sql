-- ==============================================================================
-- 4. LIMPEZA TOTAL DE POLÍTICAS ANTERIORES (IDEMPOTÊNCIA)
-- ==============================================================================

DO $$
DECLARE
    pol RECORD;
BEGIN
    FOR pol IN
        SELECT policyname, tablename
        FROM pg_policies
        WHERE schemaname = 'public'
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', pol.policyname, pol.tablename);
    END LOOP;
END $$;

