-- 5.1 ADMIN_USERS (ISOLAMENTO TOTAL CONTRA ACESSO ANÔNIMO E LEITURA PÚBLICA)
-- Nenhum acesso direto público (0 registros retornados a atacantes anônimos)
CREATE POLICY "admin_users_deny_anon"
ON public.admin_users FOR SELECT
TO anon
USING (false);

CREATE POLICY "admin_users_admin_only"
ON public.admin_users FOR ALL
TO authenticated, service_role
USING (
    auth.jwt() ->> 'role' = 'admin' OR 
    (auth.jwt() ->> 'email') = email OR
    current_user = 'service_role'
)
WITH CHECK (
    auth.jwt() ->> 'role' = 'admin' OR 
    current_user = 'service_role'
);

