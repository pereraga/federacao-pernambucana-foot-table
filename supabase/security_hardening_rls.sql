-- 10. FUNÇÃO RPC DE AUTENTICAÇÃO INSTITUCIONAL SEGURA
CREATE OR REPLACE FUNCTION public.autenticar_gestor_institucional(
    p_email TEXT,
    p_senha_plana TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_admin RECORD;
BEGIN
    p_email := lower(trim(p_email));
    
    SELECT * INTO v_admin
    FROM public.admin_users
    WHERE lower(email) = p_email 
       OR lower(email) = p_email || '@foot-table.pe.org'
       OR lower(email) = p_email || '@foot-table.pe.gov.br'
    LIMIT 1;

    IF v_admin.id IS NULL THEN
        RETURN jsonb_build_object('success', false, 'message', 'Credenciais inválidas.');
    END IF;

    IF v_admin.senha = p_senha_plana THEN
        RETURN jsonb_build_object(
            'success', true,
            'user', jsonb_build_object(
                'id', v_admin.id,
                'nome', v_admin.nome,
                'cargo', v_admin.cargo,
                'email', v_admin.email
            )
        );
    ELSE
        RETURN jsonb_build_object('success', false, 'message', 'Credenciais inválidas.');
    END IF;
END;
$$;
