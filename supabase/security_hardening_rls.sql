-- ==============================================================================
-- 6. FUNÇÃO RPC SECURITY DEFINER BLINDADA (SEARCH_PATH ESTÁTICO)
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.autenticar_gestor_institucional(
    p_email TEXT,
    p_senha_plana TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions, pg_temp
AS $$
DECLARE
    v_admin RECORD;
BEGIN
    p_email := lower(trim(p_email));

    SELECT * INTO v_admin
    FROM public.admin_users
    WHERE lower(email) = p_email OR lower(email) = p_email || '@foot-table.pe.org'
    LIMIT 1;

    IF v_admin.id IS NULL THEN
        RETURN jsonb_build_object('success', false, 'message', 'Não autorizado');
    END IF;

    IF v_admin.locked_until IS NOT NULL AND v_admin.locked_until > now() THEN
        RETURN jsonb_build_object('success', false, 'message', 'Acesso temporariamente restrito');
    END IF;

    IF v_admin.senha_hash = crypt(p_senha_plana, v_admin.senha_hash) THEN
        UPDATE public.admin_users
        SET failed_attempts = 0, locked_until = NULL, last_login = now()
        WHERE id = v_admin.id;

        RETURN jsonb_build_object(
            'success', true,
            'user', jsonb_build_object(
                'id', v_admin.id,
                'email', v_admin.email,
                'role', 'admin'
            )
        );
    ELSE
        UPDATE public.admin_users
        SET failed_attempts = failed_attempts + 1,
            locked_until = CASE WHEN failed_attempts + 1 >= 5 THEN now() + interval '15 minutes' ELSE NULL END
        WHERE id = v_admin.id;

        RETURN jsonb_build_object('success', false, 'message', 'Não autorizado');
    END IF;
END;
$$;

-- Revoga execução pública e anônima irrestrita
REVOKE ALL ON FUNCTION public.autenticar_gestor_institucional(TEXT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.autenticar_gestor_institucional(TEXT, TEXT) TO anon, authenticated, service_role;
